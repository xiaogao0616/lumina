'use client'

import Link from 'next/link'
import { useMemo, useState } from 'react'
import { ArrowRight, RotateCcw, Undo2 } from 'lucide-react'
import { Feedback, Learned, LessonShell, PredictList, TestList, allWords, useSolvedWhen, type LessonStep, type StepProps } from './lesson-kit'
import { parseGrammar, testMembership, type Grammar } from '../lib/cfg'

/**
 * Lesson 5: context-free grammars. The learner derives strings by tapping rules, sees that a
 * grammar can generate aⁿbⁿ (which no DFA can), then writes a grammar of their own.
 */

const grammarOf = (text: string): Grammar => {
  const parsed = parseGrammar(text)
  if (!parsed.ok) throw new Error(parsed.message)
  return parsed.grammar
}
const derives = (grammar: Grammar, word: string) => testMembership(grammar, word).status === 'accepted'

type Rule = { head: string; body: string }
const show = (body: string) => body || 'ε'

/**
 * A derivation you drive by tapping rules. Each tap rewrites the leftmost nonterminal, which is
 * how Sipser's leftmost derivations go, so the learner never has to choose where to apply it.
 */
function Derive({ rules, target, onSolved }: { rules: Rule[]; target: string; onSolved: () => void }) {
  const [forms, setForms] = useState<string[]>([rules[0].head])
  const current = forms[forms.length - 1]
  const at = Array.from(current).findIndex(char => /[A-Z]/.test(char))
  const done = at === -1
  const apply = (rule: Rule) => {
    const chars = Array.from(current)
    if (chars[at] !== rule.head) return
    const next = [...chars.slice(0, at), rule.body, ...chars.slice(at + 1)].join('')
    // Keep the form short enough to read; nothing in these lessons needs more.
    if (Array.from(next).length > 16) return
    setForms([...forms, next])
    if (next === target) onSolved()
  }
  return <div className="lesson-derive">
    <p className="lesson-derivation" aria-live="polite">
      {forms.map((form, index) => <span key={index}>{index > 0 && <i aria-hidden="true">⇒</i>}<code className={index === forms.length - 1 ? 'is-current' : ''}>{form || 'ε'}</code></span>)}
    </p>
    <div className="lesson-row">
      {rules.map(rule => <button key={rule.body} type="button" className="lesson-chip" disabled={done || Array.from(current)[at] !== rule.head} onClick={() => apply(rule)}>
        {rule.head} → {show(rule.body)}
      </button>)}
      <button type="button" className="text-button" disabled={forms.length < 2} onClick={() => setForms(forms.slice(0, -1))}><Undo2 size={13} aria-hidden="true" /> Undo</button>
      <button type="button" className="text-button" onClick={() => setForms([rules[0].head])}><RotateCcw size={13} aria-hidden="true" /> Reset</button>
    </div>
    {done && current !== target && <Feedback ok={false}>No variables left, so <code>{current || 'ε'}</code> is a finished string, but it isn’t <code>{target}</code>. Undo a step or reset.</Feedback>}
  </div>
}

const ANBN = grammarOf('S → aSb | ε')

/** 1. Rewrite rules. */
function StepRules({ onSolved, solved }: StepProps) {
  return <>
    <p>A <b>context-free grammar</b> builds strings instead of reading them. It has <b>rules</b> that say how a <b>variable</b> (a capital letter) may be replaced. This grammar has two rules for S:</p>
    <p className="lesson-grammar"><code>S → aSb | ε</code></p>
    <p>Start from S and keep replacing a variable using a rule. When no variables are left, you have a string the grammar <b>generates</b>. Each step is written with ⇒.</p>
    <p className="lesson-task">Tap rules to derive <code>aabb</code>.</p>
    <Derive rules={[{ head: 'S', body: 'aSb' }, { head: 'S', body: '' }]} target="aabb" onSolved={onSolved} />
    {solved && <Feedback ok>That’s a <b>derivation</b>: <code>S ⇒ aSb ⇒ aaSbb ⇒ aabb</code>. Each use of S → aSb adds one a <b>and</b> one b, in the middle.</Feedback>}
  </>
}

/** 2. The grammar's language. */
function StepLanguage({ onSolved }: StepProps) {
  return <>
    <p>The set of strings a grammar can generate is its <b>language</b>. Languages generated by such grammars are called <b>context-free</b>.</p>
    <p className="lesson-grammar"><code>S → aSb | ε</code></p>
    <p className="lesson-task">Which strings can S generate? ε is the empty string.</p>
    <PredictList words={['ab', 'aabb', 'abab', 'aab', '']} truth={word => derives(ANBN, word)} onSolved={onSolved} yes="generates" no="can’t"
      success={<>Right. This grammar generates exactly <b>aⁿbⁿ</b>, the language lesson 4 proved no DFA can recognize. A grammar can count because S always sits in the middle, waiting to add a matching pair.</>} />
  </>
}

/** 3. Nesting: balanced parentheses. */
function StepNesting({ onSolved, solved }: StepProps) {
  return <>
    <p>Grammars are good at <b>nesting</b>, which is why programming languages are defined with them. This one generates balanced parentheses:</p>
    <p className="lesson-grammar"><code>S → (S)S | ε</code></p>
    <p>Read it as: a balanced string is empty, or a pair of parentheses with something balanced inside and something balanced after.</p>
    <p className="lesson-task">Derive <code>()()</code>. Each tap rewrites the leftmost S.</p>
    <Derive rules={[{ head: 'S', body: '(S)S' }, { head: 'S', body: '' }]} target="()()" onSolved={onSolved} />
    {solved && <Feedback ok>Nice: <code>S ⇒ (S)S ⇒ ()S ⇒ ()(S)S ⇒ ()()S ⇒ ()()</code>. The first S inside a pair can hold another whole balanced string, so nesting can go as deep as you like.</Feedback>}
  </>
}

const isEvenPalindrome = (word: string) => word.length % 2 === 0 && word === Array.from(word).reverse().join('')
const PAL_TESTS = ['', 'aa', 'abba', 'baab', 'ab', 'aba', 'abab', 'aab']
const ALL_PAL_WORDS = allWords(['a', 'b'], 6)

/** 4. Write a grammar. */
function StepWrite({ onSolved, solved }: StepProps) {
  const [text, setText] = useState('S → ')
  const parsed = useMemo(() => parseGrammar(text), [text])
  const grammar = parsed.ok ? parsed.grammar : null
  const outside = grammar ? grammar.terminals.find(symbol => symbol !== 'a' && symbol !== 'b') : undefined
  const usable = grammar && !outside ? grammar : null
  const rows = PAL_TESTS.map(word => ({ word, want: isEvenPalindrome(word), got: usable ? derives(usable, word) : null }))
  const counterexample = useMemo(() => usable ? ALL_PAL_WORDS.find(word => derives(usable, word) !== isEvenPalindrome(word)) ?? null : null, [usable])
  const passing = !!usable && counterexample === null
  useSolvedWhen(passing, solved, onSolved)
  return <>
    <p>Your turn. Write a grammar for <b>even-length palindromes</b> over a and b: strings that read the same backwards and have even length, like ε, aa, abba, baab.</p>
    <label className="lesson-input">
      <span>Grammar</span>
      <textarea value={text} onChange={event => setText(event.target.value)} rows={2} spellCheck={false} autoCapitalize="off" autoComplete="off" />
    </label>
    <p className="lesson-hint">Separate choices with <code>|</code>. For the empty string write ε or leave a choice empty. Typing a minus and a greater-than sign works as the arrow.</p>
    <TestList rows={rows} yes="should generate" no="shouldn’t" />
    {passing
      ? <Feedback ok>Correct for every string up to length 6. <code>S → aSa | bSb | ε</code> wraps a matching letter on each side, just like aSb did for aⁿbⁿ.</Feedback>
      : !parsed.ok ? <Feedback ok={false}>{parsed.message}</Feedback>
      : outside ? <Feedback ok={false}>Use only the letters a and b. <code>{outside}</code> is not one of them.</Feedback>
      : counterexample !== null ? <Feedback ok={false}>Not yet. It gets <code>{counterexample || 'ε'}</code> wrong: that string {isEvenPalindrome(counterexample) ? 'is an even palindrome but isn’t generated' : 'is generated but isn’t an even palindrome'}. Hint: copy the idea of S → aSb, but put the same letter on both sides.</Feedback>
      : null}
  </>
}

/** 5. Recap. */
function StepDone() {
  return <>
    <Learned items={[
      <>A <b>context-free grammar</b> has variables, terminals (the letters) and rules like <code>S → aSb</code>.</>,
      <>A <b>derivation</b> rewrites variables until only letters are left. The strings you can reach form the grammar’s <b>language</b>.</>,
      <>Grammars can match and nest, so they generate languages like <b>aⁿbⁿ</b> that are <b>not regular</b>. Every regular language is context-free too.</>,
      <>The machine that matches grammars is the <b>pushdown automaton</b>: an NFA plus a stack to remember what still needs matching.</>,
    ]} />
    <p>That’s the end of the lessons for now. Turing machines come later.</p>
    <div className="lesson-next">
      <Link className="secondary-button" href="/cfg">Open the CFG workspace <ArrowRight size={14} aria-hidden="true" /></Link>
      <Link className="secondary-button" href="/pda">Try a pushdown automaton</Link>
    </div>
  </>
}

const steps: LessonStep[] = [
  { title: 'Rules that rewrite', Body: StepRules },
  { title: 'What can S make?', Body: StepLanguage },
  { title: 'Nesting', Body: StepNesting },
  { title: 'Write a grammar', Body: StepWrite },
  { title: 'What you learned', Body: StepDone, free: true },
]

export function CfgLesson() {
  return <LessonShell id="cfg" steps={steps} />
}
